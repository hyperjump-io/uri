// Generates src/patterns.js, the built-in schemes' patterns, from their RFCs' ABNF. Run `npm run generate` after
// changing them. src/patterns.test.js fails when src/patterns.js isn't what this generates.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { abnf } from "@hyperjump/abnf";
import { asciiFragment, asciiPath, asciiQuery, host, path } from "../src/abnf.js";

// RFC 8141 §2, without namestring and assigned-name, which the scheme's rules and the patterns below are. RFC 8141 says
// alphanum is RFC 3986's, but RFC 3986 Appendix D removed it, so it's RFC 2396's.
const urnRules = `
  NID           = (alphanum) 0*30(ldh) (alphanum)
  ldh           = alphanum / "-"
  NSS           = pchar *(pchar / "/")
  r-component   = pchar *( pchar / "/" / "?" )
  q-component   = pchar *( pchar / "/" / "?" )
  f-component   = fragment
  alphanum      = ALPHA / DIGIT
`;

// DID 1.1 §3.1, verbatim, without did, which the scheme's rules and the patterns below are, and without pct-encoded,
// which is RFC 3986's
const didRules = `
  method-name        = 1*method-char
  method-char        = %x61-7A / DIGIT
  method-specific-id = *( *idchar ":" ) 1*idchar
  idchar             = ALPHA / DIGIT / "." / "-" / "_" / pct-encoded
`;

/** @type [name: string, comment: string, pattern: RegExp][] */
const patterns = [
  [
    "httpHost",
    `RFC 9110 §4.2.1: "A sender MUST NOT generate an "http" URI with an empty host identifier. A recipient that processes
such a URI reference MUST reject it as invalid." The same for https (§4.2.2).`,
    abnf(host)`IP-literal / 1*( unreserved / pct-encoded / sub-delims )`
  ],
  [
    "filePath",
    `RFC 8089 §2: auth-path = [ file-auth ] path-absolute, and local-path = path-absolute`,
    abnf(path)`path-absolute`
  ],
  [
    "urnPath",
    `RFC 8141 §2: assigned-name = "urn" ":" NID ":" NSS. A URN is ASCII in an IRI too: RFC 8141 "does not extend the URN
syntax to allow direct use of characters outside the ASCII range".`,
    abnf(asciiPath)`NID ":" NSS ${urnRules}`
  ],
  [
    "urnQuery",
    `RFC 8141 §2: rq-components = [ "?+" r-component ] [ "?=" q-component ], which starts with the query's delimiter, so
it's written for what's after the "?"`,
    abnf(asciiQuery)`"+" r-component [ "?=" q-component ] / "=" q-component ${urnRules}`
  ],
  [
    "urnFragment",
    `RFC 8141 §2: f-component = fragment`,
    abnf(asciiFragment)`f-component ${urnRules}`
  ],
  [
    "didPath",
    `DID 1.1 §3.2: did-url = did path-abempty [ "?" query ] [ "#" fragment ], where did = "did:" method-name ":"
method-specific-id. Every rule is ASCII, so a DID is ASCII in an IRI too.`,
    abnf(asciiPath)`method-name ":" method-specific-id path-abempty ${didRules}`
  ],
  [
    "didQuery",
    `DID 1.1 §3.2: a DID URL's query is RFC 3986's, which is ASCII`,
    abnf(asciiQuery)`query`
  ],
  [
    "didFragment",
    `DID 1.1 §3.2: a DID URL's fragment is RFC 3986's, which is ASCII`,
    abnf(asciiFragment)`fragment`
  ],
  [
    "uuidNss",
    `RFC 9562 §4, verbatim`,
    abnf(asciiPath)`
      UUID     = 4hexOctet "-"
                 2hexOctet "-"
                 2hexOctet "-"
                 2hexOctet "-"
                 6hexOctet
      hexOctet = HEXDIG HEXDIG
      DIGIT    = %x30-39
      HEXDIG   = DIGIT / "A" / "B" / "C" / "D" / "E" / "F"
    `
  ]
];

/** @type () => string */
export const generate = () => {
  let file = `// Generated by scripts/generate-patterns.js from the built-in schemes' ABNF, which is there. Don't edit it: change
// the script and run \`npm run generate\`.
`;
  for (const [name, comment, pattern] of patterns) {
    const literal = `/${pattern.source}/${pattern.flags}`;
    file += `\n${comment.replaceAll(/^/gm, "// ")}\n`;
    file += `export const ${name} = ${literal};\n`;
  }
  return file;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL("../src/patterns.js", import.meta.url), generate());
}
